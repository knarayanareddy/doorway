#!/usr/bin/env node
/**
 * Sign the routes bundle with Ed25519 (review B4).
 *
 *   node scripts/sign-routes.mjs --gen-dev-key     create a DEV keypair, pin its public half
 *   node scripts/sign-routes.mjs                    sign with $DOORWAY_SIGNING_KEY_FILE (default .keys/dev-signing.pem)
 *   node scripts/sign-routes.mjs --file=<path>      sign another bundle (routes.demo.json) with the same key
 *
 * Production key: node scripts/gen-prod-key.mjs <absolute path outside the repo>, then pin, then sign.
 * See SECURITY.md "Key rotation".
 *
 * The private key never lives in the repo. The pinned public key
 * (packages/doorway/src/pubkey.js) is what the Door verifies against. The key
 * generated by --gen-dev-key is for development only: before any pilot, generate
 * the production key offline, pin ITS public half, and store the private half
 * where only the release owner can reach it.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { signedBytes, bytesToB64u } from '../packages/core/src/bundle.js';

const ROOT = new URL('..', import.meta.url).pathname;
// --file=<path> signs another bundle with the same key (the demo record: routes.demo.json).
const fileArg = process.argv.find((a) => a.startsWith('--file='));
const ROUTES = fileArg ? path.resolve(fileArg.slice('--file='.length)) : path.join(ROOT, 'packages/doorway/src/routes.nl.json');
const PUBKEY = path.join(ROOT, 'packages/doorway/src/pubkey.js');

if (process.argv.includes('--gen-dev-key')) {
  const { publicKey, privateKey } = crypto.generateKeyPairSync('ed25519');
  const dir = path.join(ROOT, '.keys');
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, 'dev-signing.pem');
  fs.writeFileSync(file, privateKey.export({ type: 'pkcs8', format: 'pem' }), { mode: 0o600 });
  const raw = publicKey.export({ type: 'spki', format: 'der' }).subarray(-32);
  fs.writeFileSync(PUBKEY,
`/**
 * Pinned Ed25519 public key (raw, base64url) used by the Door to verify the routes bundle.
 * KEY: DEV — replace with the production public key before any pilot (see scripts/sign-routes.mjs).
 */
export const PUBLIC_KEY_RAW_B64U = '${bytesToB64u(raw)}';
export const KEY_ID = 'dev';
`);
  console.log(`dev private key: ${file} (gitignored — keep it out of the repo)\npinned public key written to ${path.relative(ROOT, PUBKEY)}`);
}

const keyFile = process.env.DOORWAY_SIGNING_KEY_FILE || path.join(ROOT, '.keys/dev-signing.pem');
if (!fs.existsSync(keyFile)) { console.error(`no signing key at ${keyFile}`); process.exit(1); }
const bundle = JSON.parse(fs.readFileSync(ROUTES, 'utf8'));
delete bundle.sig;
const sig = crypto.sign(null, signedBytes(bundle), crypto.createPrivateKey(fs.readFileSync(keyFile)));
bundle.sig = bytesToB64u(new Uint8Array(sig));
fs.writeFileSync(ROUTES, JSON.stringify(bundle, null, 1) + '\n');
console.log(`signed ${path.relative(ROOT, ROUTES)} (version ${bundle.version}, validUntil ${bundle.validUntil})`);
